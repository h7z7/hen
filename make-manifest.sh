#!/bin/bash
# Gera o cache.appcache a partir dos arquivos que a pagina realmente usa.
#
# Por que AppCache: o navegador do PS4 ignora headers HTTP do GitHub Pages e
# precisa de cache offline. e e o mecanismo que os hosts de exploit usam.
#
# Por que hashes: so um manifest alterado refaz o cache de um arquivo; ao
# listar o hash do conteudo, qualquer edicao muda o manifest e o console
# busca a versao nova. (Aula classica do mecanismo AppCache.)
#
# Rode depois de mudar qualquer arquivo abaixo e commite o resultado.
set -e
cd "$(dirname "$0")"
OUT=cache.appcache
FILES="index.html dashboard.css dashboard.js
       jb.html jb.js core.js mem.js int64.js ps4_offsets.js afterglow.js
       patchset-1200.bin patchset-1202.bin patchset-1250.bin patchset-1252.bin
       patchset-1300.bin patchset-1302.bin patchset-1304.bin patchset-1350.bin
       patchset-1352.bin patchset-1400.bin patchset-1402.bin
       hen.bin goldhen.bin"

{
  echo "CACHE MANIFEST"
  echo "# generated by make-manifest.sh -- do not edit by hand"
  echo "# $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo
  for f in $FILES; do
    [ -f "$f" ] || { echo "missing: $f" >&2; exit 1; }
    printf '%s #%s\n' "$f" "$(sha256sum "$f" | cut -c1-32)"
  done
  echo
  # jb.html e alcancado como jb.html?mode=... e o cache casa URLs COM a query
  # string -- o fallback serve a pagina cacheada para qualquer jb.html?...
  # ainda nao vista, mantendo a query (a pagina le os proprios parametros).
  echo "FALLBACK:"
  echo "jb.html jb.html"
  echo
  echo "NETWORK:"
  echo "*"
} > "$OUT"
echo "$OUT: $(grep -cE '^[^#[:space:]]+ #' "$OUT") entradas, $(wc -c < "$OUT") bytes"
